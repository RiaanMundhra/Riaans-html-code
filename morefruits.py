class fruits:

    taste = "Sweet"

    def __init__(self, name, size, colour):
        self.name = name
        self.size = size
        self.colour = colour

aapple = fruits("apple", "small", "redish maroon")
print(aapple.taste)
print(aapple.name)
print(aapple.colour)
print(aapple.size)
bananaj = fruits("banana", "giant", "yellow")
print(bananaj.name)
print(bananaj.colour)
print(bananaj.size)
